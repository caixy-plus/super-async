CREATE TABLE IF NOT EXISTS async_tasks
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_type      VARCHAR(64)  NOT NULL,
    task_key       VARCHAR(255) NOT NULL UNIQUE,
    payload        TEXT         NOT NULL,
    priority       INT          NOT NULL DEFAULT 5,
    status         VARCHAR(20)  NOT NULL,
    retry_count    INT          NOT NULL DEFAULT 0,
    max_retry      INT          NOT NULL DEFAULT 3,
    execute_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    timeout_at     TIMESTAMP WITH TIME ZONE,
    result_payload TEXT,
    error_msg      TEXT,
    worker_node    VARCHAR(64),
    worker_tag     VARCHAR(64),
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_async_tasks_status_execute_at ON async_tasks (status, execute_at);
CREATE INDEX IF NOT EXISTS idx_async_tasks_status_timeout_at ON async_tasks (status, timeout_at);
CREATE INDEX IF NOT EXISTS idx_async_tasks_task_type ON async_tasks (task_type);
CREATE INDEX IF NOT EXISTS idx_async_tasks_worker_node ON async_tasks (worker_node);

CREATE TABLE IF NOT EXISTS scheduled_jobs
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_name        VARCHAR(64)  NOT NULL UNIQUE,
    task_type       VARCHAR(64)  NOT NULL,
    task_key        VARCHAR(255) NOT NULL,
    payload         TEXT,
    cron_expression VARCHAR(64)  NOT NULL,
    worker_tag      VARCHAR(64),
    enabled         BOOLEAN      NOT NULL DEFAULT true,
    description     VARCHAR(255),
    last_trigger_at TIMESTAMP WITH TIME ZONE,
    next_trigger_at TIMESTAMP WITH TIME ZONE,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_scheduled_jobs_enabled_next_trigger ON scheduled_jobs (enabled, next_trigger_at);
CREATE INDEX IF NOT EXISTS idx_scheduled_jobs_job_name ON scheduled_jobs (job_name);

CREATE TABLE IF NOT EXISTS workflow_definitions
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(128) NOT NULL,
    description TEXT,
    dag_json    TEXT         NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS workflow_instances
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    definition_id   BIGINT       NOT NULL,
    status          VARCHAR(20)  NOT NULL,
    context_payload TEXT,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS workflow_node_instances
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workflow_instance_id BIGINT       NOT NULL,
    node_id            VARCHAR(64)  NOT NULL,
    node_name          VARCHAR(128),
    task_type          VARCHAR(64)  NOT NULL,
    task_key           VARCHAR(255) UNIQUE,
    payload            TEXT,
    status             VARCHAR(20)  NOT NULL,
    retry_count        INT          NOT NULL DEFAULT 0,
    max_retry          INT          NOT NULL DEFAULT 3,
    upstream_nodes     TEXT,
    downstream_nodes   TEXT,
    execute_mode       VARCHAR(10)  NOT NULL DEFAULT 'SERIAL',
    task_id            BIGINT,
    result_payload     TEXT,
    error_msg          TEXT,
    started_at         TIMESTAMP WITH TIME ZONE,
    completed_at       TIMESTAMP WITH TIME ZONE,
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
